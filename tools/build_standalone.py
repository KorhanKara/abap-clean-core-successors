#!/usr/bin/env python3
"""Build standalone/zclean_core_successors.abap: the report and both classes in one
source, for systems without abapGit. Paste it into a new report in SE38.

Usage:
    python tools/build_standalone.py
"""
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))
SRC = os.path.join(ROOT, "src")
TARGET = os.path.join(ROOT, "standalone", "zclean_core_successors.abap")

LOCAL_NAMES = [("zcl_clean_core_successors", "lcl_mapping")]
SCREEN_START = "\nCLASS lcl_report DEFINITION FINAL.\n"


def read(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def localize(source):
    source = re.sub(r"DEFINITION\n\s*PUBLIC FINAL\n\s*CREATE PUBLIC\.", "DEFINITION FINAL.", source)
    for global_name, local_name in LOCAL_NAMES:
        source = re.sub(rf"\b{global_name}\b", local_name, source, flags=re.IGNORECASE)
    return source.rstrip("\n") + "\n"


def selection_texts():
    xml = read("zclean_core_successors.prog.xml")
    texts = []
    for key, entry in re.findall(r"<KEY>([^<]+)</KEY>\s*<ENTRY>([^<]+)</ENTRY>", xml):
        text = entry.strip().replace("'", "''")
        texts.append(f"  %_{key.lower()}_%_app_%-text = '{text}'.")
    return "INITIALIZATION.\n" + "\n".join(texts) + "\n\n"


def build():
    report = localize(read("zclean_core_successors.prog.abap"))
    screen, _, rest = report.partition(SCREEN_START)
    if not rest:
        raise SystemExit("report layout changed: lcl_report definition not found")
    classes = localize(read("zcl_clean_core_successors.clas.abap"))
    tail_marker = "\nAT SELECTION-SCREEN OUTPUT.\n"
    body, _, events = ("\n" + SCREEN_START.lstrip("\n") + rest).partition(tail_marker)
    if not events:
        raise SystemExit("report layout changed: AT SELECTION-SCREEN OUTPUT not found")

    header = ("* Generated by tools/build_standalone.py from src/. Do not edit here.\n"
              "* Source: https://github.com/KorhanKara/abap-clean-core-successors\n")
    source = (header + screen.rstrip("\n") + "\n\n\n" + classes + "\n" + body.rstrip("\n") + "\n\n\n"
              + selection_texts() + tail_marker.lstrip("\n") + events)
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    print(f"{source.count(chr(10))} lines written to {TARGET}")


if __name__ == "__main__":
    build()
